/**
 * Assembles the browser playground into `docs/playground/`.
 *
 * Run after `npm run build` (compiled library in `dist/`) and `typedoc` (which
 * empties and recreates `docs/`). It produces:
 *
 * - `lib/`           the compiled ESM library, loaded by the playground at run time;
 * - `typings.json`   the `.d.ts` files, fed to the editor for autocomplete;
 * - `examples.json`  every `@example` from the sources turned into a
 *                    self-contained program (imports added, variables from
 *                    earlier examples of the same declaration pulled in);
 * - `vendor/`        Node-style `util.format` for console output;
 * - `manifest.json`  package version and module list;
 * - the static files from `playground/`.
 */
import { cp, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectExamples, MODULES, normalize } from './lib/examples.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const out = join(root, 'docs', 'playground');

const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

async function walk(dir) {
    const files = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) files.push(...(await walk(path)));
        else files.push(path);
    }
    return files;
}

const posix = (path) => path.split('\\').join('/');

// ---------------------------------------------------------------------------
// Static assets, library, typings, vendor files
// ---------------------------------------------------------------------------

async function copyStatic() {
    await mkdir(out, { recursive: true });
    await cp(join(root, 'playground'), out, { recursive: true });
}

async function copyLibrary() {
    const files = await walk(dist);
    const typings = {};
    for (const file of files) {
        const rel = posix(relative(dist, file));
        if (rel.endsWith('.d.ts')) {
            typings[rel] = await readFile(file, 'utf8');
        } else if (rel.endsWith('.js')) {
            await mkdir(dirname(join(out, 'lib', rel)), { recursive: true });
            await cp(file, join(out, 'lib', rel));
        }
    }
    await writeFile(join(out, 'typings.json'), JSON.stringify(typings));
}

async function writeVendor() {
    // node-inspect-extracted ships a UMD bundle; wrap it as an ES module so the
    // worker can import it. It gives console output identical to Node's.
    const umd = join(root, 'node_modules', 'node-inspect-extracted', 'dist', 'inspect.js');
    const source = await readFile(umd, 'utf8');
    const wrapped = [
        '// Generated by scripts/build-playground.mjs from node-inspect-extracted (MIT).',
        'const module = { exports: {} };',
        'const exports = module.exports;',
        '(function () {',
        source,
        '}).call(globalThis);',
        'export const { format, inspect } = module.exports;',
        '',
    ].join('\n');
    await mkdir(join(out, 'vendor'), { recursive: true });
    await writeFile(join(out, 'vendor', 'inspect.mjs'), wrapped);
}

/** Examples that cannot run (unresolved names) are left out with a warning. */
async function buildExamples() {
    const examples = {};
    for (const { file, code, program, unresolved, diagnostics } of await collectExamples()) {
        if (unresolved) {
            console.warn(`warning: example skipped (not runnable): ${file}: ${diagnostics[0]}`);
            continue;
        }
        examples[normalize(code)] = program;
    }
    await writeFile(join(out, 'examples.json'), JSON.stringify(examples));
    return Object.keys(examples).length;
}

// ---------------------------------------------------------------------------

if (!existsSync(dist)) throw new Error('dist/ not found: run `npm run build` first.');
if (!existsSync(join(root, 'docs'))) throw new Error('docs/ not found: run `typedoc` first.');

await copyStatic();
await copyLibrary();
await writeVendor();
const exampleCount = await buildExamples();
await writeFile(join(out, 'manifest.json'), JSON.stringify({ version: pkg.version, modules: MODULES }));

console.log(`Playground written to docs/playground (${exampleCount} examples).`);
